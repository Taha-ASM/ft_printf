#include "ft_printf.h"

int	ft_putnbr(int n)
{
	int		count;
	char	c;

	count = 0;
	if (n == -2147483648)
	{
		count += write(1, "-2147483648", 11);
		return (count);
	}
	if (n < 0)
	{
		n = n * -1;
		count += write(1, "-", 1);
	}
	if (0 <= n && n <= 9)
	{
		c = n + '0';
		count += write(1, &c, 1);
	}
	if (n >= 10)
	{
		count += ft_putnbr(n / 10);
		count += ft_putnbr(n % 10);
	}
	return (count);
}
